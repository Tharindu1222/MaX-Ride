// Writes Android string resource + iOS xcconfig from GOOGLE_MAPS_API_KEY.
// Usage: node scripts/sync-maps-key.cjs
const fs = require('fs');
const path = require('path');

const monorepo = path.resolve(__dirname, '..');

function loadDotEnv(file) {
  if (!fs.existsSync(file)) return {};
  const out = {};
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith('#') || !t.includes('=')) continue;
    const i = t.indexOf('=');
    const k = t.slice(0, i).trim();
    const v = t.slice(i + 1).trim().replace(/^['"]|['"]$/g, '');
    out[k] = v;
  }
  return out;
}

function resolveKey() {
  if (process.env.GOOGLE_MAPS_API_KEY && process.env.GOOGLE_MAPS_API_KEY.trim()) {
    return process.env.GOOGLE_MAPS_API_KEY.trim();
  }
  if (process.env.MAPS_API_KEY && process.env.MAPS_API_KEY.trim()) {
    return process.env.MAPS_API_KEY.trim();
  }
  for (const file of [
    path.join(monorepo, '.env'),
    path.join(monorepo, 'apps/api/.env'),
  ]) {
    const map = loadDotEnv(file);
    if (map.GOOGLE_MAPS_API_KEY && map.GOOGLE_MAPS_API_KEY.trim()) {
      return map.GOOGLE_MAPS_API_KEY.trim();
    }
    if (map.MAPS_API_KEY && map.MAPS_API_KEY.trim()) {
      return map.MAPS_API_KEY.trim();
    }
  }
  for (const app of ['driver', 'passenger']) {
    const lp = path.join(monorepo, 'apps', app, 'android', 'local.properties');
    if (!fs.existsSync(lp)) continue;
    for (const line of fs.readFileSync(lp, 'utf8').split(/\r?\n/)) {
      const t = line.trim();
      if (t.startsWith('maps.apiKey=')) {
        const v = t.slice('maps.apiKey='.length).trim();
        if (v) return v;
      }
    }
  }
  return '';
}

const key = resolveKey();
const escapeXml = (s) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');

const xml = `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Generated by scripts/sync-maps-key.cjs from GOOGLE_MAPS_API_KEY -->
    <string name="google_maps_api_key" translatable="false">${escapeXml(key)}</string>
</resources>
`;

const bodyIos = `// Generated by scripts/sync-maps-key.cjs — do not commit secrets
GOOGLE_MAPS_API_KEY=${key}
`;

const androidTargets = [
  path.join(monorepo, 'apps/passenger/android/app/src/main/res/values/google_maps_api.xml'),
  path.join(monorepo, 'apps/driver/android/app/src/main/res/values/google_maps_api.xml'),
];

const iosTargets = [
  path.join(monorepo, 'apps/passenger/ios/Flutter/MapsSecrets.xcconfig'),
  path.join(monorepo, 'apps/driver/ios/Flutter/MapsSecrets.xcconfig'),
];

for (const file of androidTargets) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, xml, 'utf8');
  console.log('Android:', path.relative(monorepo, file), key ? '(key set)' : '(EMPTY)');
}

for (const file of iosTargets) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, bodyIos, 'utf8');
  console.log('iOS:', path.relative(monorepo, file));
}

for (const app of ['passenger', 'driver']) {
  const lp = path.join(monorepo, 'apps/' + app + '/android/local.properties');
  if (!fs.existsSync(lp) || !key) continue;
  let text = fs.readFileSync(lp, 'utf8');
  if (/^maps\.apiKey=/m.test(text)) {
    text = text.replace(/^maps\.apiKey=.*$/m, 'maps.apiKey=' + key);
  } else {
    text = text.replace(/\s*$/, '\nmaps.apiKey=' + key + '\n');
  }
  fs.writeFileSync(lp, text, 'utf8');
}

if (!key) {
  console.warn('GOOGLE_MAPS_API_KEY is empty — maps tiles will not load.');
  process.exitCode = 1;
} else {
  console.log('OK — sync complete');
}
